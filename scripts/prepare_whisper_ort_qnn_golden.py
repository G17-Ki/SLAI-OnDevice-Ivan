def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument("--wav", type=Path, default=DEFAULT_WAV)
    parser.add_argument("--model-archive", type=Path, default=DEFAULT_MODEL_ARCHIVE)
    parser.add_argument("--voice-ai-archive", type=Path, default=DEFAULT_VOICE_ARCHIVE)
    parser.add_argument("--qai-wheel", type=Path, default=DEFAULT_QAI_WHEEL)
    parser.add_argument(
        "--transformers-wheel", type=Path, default=DEFAULT_TRANSFORMERS_WHEEL
    )
    parser.add_argument(
        "--mlx-whisper-wheel", type=Path, default=DEFAULT_MLX_WHISPER_WHEEL
    )
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="replace only named fixture files whose bytes do not match",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    manifest = generate_bundle(
        output_dir=args.output_dir.expanduser().resolve(),
        manifest_path=args.manifest.expanduser().resolve(),
        wav_path=args.wav.expanduser().resolve(),
        model_archive=args.model_archive.expanduser().resolve(),
        voice_archive=args.voice_ai_archive.expanduser().resolve(),
        qai_wheel=args.qai_wheel.expanduser().resolve(),
        transformers_wheel=args.transformers_wheel.expanduser().resolve(),
        mlx_whisper_wheel=args.mlx_whisper_wheel.expanduser().resolve(),
        overwrite=args.overwrite,
    )
    print(
        json.dumps(
            {
                "artifact_count": len(manifest["artifacts"]),
                "fixture_id": manifest["fixture_id"],
                "manifest": str(args.manifest.expanduser().resolve()),
                "output_dir": str(args.output_dir.expanduser().resolve()),
                "status": "pass",
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
