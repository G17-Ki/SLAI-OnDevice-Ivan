def require_descriptor(
    value: dict[str, Any],
    *,
    dtype: str,
    shape: list[int],
    scale: float | None = None,
    zero_point: int | None = None,
    label: str,
) -> None:
    if value.get("dtype") != dtype or value.get("shape") != shape:
        raise GoldenInputError(f"release descriptor mismatch for {label}")
    if scale is None and zero_point is None:
        return
    quantization = value.get("quantization_parameters")
    if not isinstance(quantization, dict):
        raise GoldenInputError(f"missing quantization parameters for {label}")
    if scale is not None and quantization.get("scale") != scale:
        raise GoldenInputError(f"release scale mismatch for {label}")
    if zero_point is not None and quantization.get("zero_point") != zero_point:
        raise GoldenInputError(f"release zero point mismatch for {label}")


def validate_tensor_contract(metadata: dict[str, Any]) -> None:
    required_top_level = {
        "model_id": "whisper_small_quantized",
        "model_name": "Whisper-Small-Quantized",
        "runtime": "precompiled_qnn_onnx",
        "precision": "w8a16",
    }
    for key, expected in required_top_level.items():
        if metadata.get(key) != expected:
            raise GoldenInputError(f"release metadata mismatch for {key}")
    files = metadata.get("model_files")
    if not isinstance(files, dict):
        raise GoldenInputError("release metadata has no model_files object")
    encoder = files.get("encoder.onnx")
    decoder = files.get("decoder.onnx")
    if not isinstance(encoder, dict) or not isinstance(decoder, dict):
        raise GoldenInputError("release metadata is missing encoder/decoder")
    encoder_inputs = encoder.get("inputs", {})
    decoder_inputs = decoder.get("inputs", {})
    require_descriptor(
        encoder_inputs.get("input_features", {}),
        dtype="uint16",
        shape=[1, N_MELS, N_FRAMES],
        scale=FEATURE_QUANTIZATION["scale"],
        zero_point=FEATURE_QUANTIZATION["zero_point"],
        label="input_features",
    )
    require_descriptor(
        decoder_inputs.get("attention_mask", {}),
        dtype="uint16",
        shape=[1, 1, 1, DECODE_LENGTH],
        scale=MASK_QUANTIZATION["scale"],
        zero_point=MASK_QUANTIZATION["zero_point"],
        label="attention_mask",
    )
    require_descriptor(
        decoder_inputs.get("input_ids", {}),
        dtype="int32",
        shape=[1, 1],
        label="input_ids",
    )
    require_descriptor(
        decoder_inputs.get("position_ids", {}),
        dtype="int32",
        shape=[1],
        label="position_ids",
    )
    for layer in range(DECODER_LAYERS):
        require_descriptor(
            decoder_inputs.get(f"k_cache_self_{layer}_in", {}),
            dtype="uint8",
            shape=[DECODER_HEADS, 1, ATTENTION_DIMENSION // DECODER_HEADS, 199],
            zero_point=SELF_KV_ZERO_POINT,
            label=f"k_cache_self_{layer}_in",
        )
        require_descriptor(
            decoder_inputs.get(f"v_cache_self_{layer}_in", {}),
            dtype="uint8",
            shape=[DECODER_HEADS, 1, 199, ATTENTION_DIMENSION // DECODER_HEADS],
            zero_point=SELF_KV_ZERO_POINT,
            label=f"v_cache_self_{layer}_in",
        )


def parse_tiktoken(value: bytes) -> list[bytes]:
    if len(value) != TIKTOKEN["bytes"] or sha256_bytes(value) != TIKTOKEN["sha256"]:
        raise GoldenInputError("multilingual tiktoken identity mismatch")
    entries: list[bytes] = []
    for raw_line in value.splitlines():
        parts = raw_line.split()
        if len(parts) != 2:
            raise GoldenInputError("malformed multilingual tiktoken line")
        try:
            # OpenAI's final, true-empty mergeable token is represented by the
            # historical non-canonical base64 spelling ``=``.
            token = (
                b""
                if parts[0] == b"="
                else base64.b64decode(parts[0], validate=True)
            )
            rank = int(parts[1])
        except (ValueError, TypeError) as error:
            raise GoldenInputError("malformed multilingual tiktoken entry") from error
        if rank != len(entries):
            raise GoldenInputError("multilingual tiktoken ranks are not contiguous")
        entries.append(token)
    if len(entries) != SPECIAL_TOKEN_IDS["eot"]:
        raise GoldenInputError("unexpected multilingual mergeable-token count")
    if entries[188] != b"\0" or entries[50_256] != b"":
        raise GoldenInputError("multilingual tokenizer NUL/empty token mismatch")
    return entries


def build_qai_voice_vocab(entries: list[bytes]) -> bytes:
    output = bytearray()
    for token in entries:
        output.extend(token)
        if b"\0" not in token:
            output.append(0)
    return bytes(output)


def split_voice_vocab(value: bytes) -> list[bytes]:
    entries = value.split(b"\0")[:-1]
    if len(entries) != SPECIAL_TOKEN_IDS["eot"]:
        raise GoldenInputError("VoiceAI vocab entry count mismatch")
    entries[188] = b"\0"
    return entries


def decode_mergeable_tokens(entries: list[bytes], token_ids: list[int]) -> str:
    raw = b"".join(
        entries[token_id] for token_id in token_ids if 0 <= token_id < len(entries)
    )
    return raw.decode("utf-8")


